"""Shared dtype utilities for torch-neuronx.

This module provides the canonical mapping from ``torch.dtype`` to
``c10::ScalarType`` enum integers. The integer values match the
``c10::ScalarType`` enum as defined in PyTorch's
``c10/core/ScalarType.h`` (ordinal ordering generated by the
``AT_FORALL_SCALAR_TYPES_WITH_COMPLEX_AND_QINTS`` macro: Byte=0,
Char=1, Short=2, Int=3, Long=4, Half=5, Float=6, Double=7,
ComplexHalf=8, ComplexFloat=9, ComplexDouble=10, Bool=11,
quantized types=12-14, BFloat16=15, quantized types=16-17,
float8 types=23-26, additional types=27-45).

PyTorch's ``c10/core/ScalarType.h`` is the authoritative source for
these values; keep this table in sync when upgrading PyTorch.
"""

import torch

TORCH_DTYPE_TO_SCALAR_TYPE: dict[torch.dtype, int] = {
    torch.uint8: 0,  # Byte
    torch.int8: 1,  # Char
    torch.int16: 2,  # Short
    torch.int32: 3,  # Int
    torch.int64: 4,  # Long
    torch.float16: 5,  # Half
    torch.float32: 6,  # Float
    torch.float64: 7,  # Double
    # torch.complex32: 8,   # ComplexHalf (not commonly used)
    torch.complex64: 9,  # ComplexFloat
    torch.complex128: 10,  # ComplexDouble
    torch.bool: 11,  # Bool
    # Quantized types: 12-14, 16-17
    torch.bfloat16: 15,  # BFloat16
    # Float8 types: 23-26
    # Additional types: 27-45
}


def torch_dtype_to_scalar_type(dtype: torch.dtype) -> int | None:
    """Convert a ``torch.dtype`` to its ``c10::ScalarType`` integer value.

    Args:
        dtype: PyTorch dtype to convert.

    Returns:
        The integer value corresponding to the ``c10::ScalarType`` enum, or
        ``None`` if the dtype is not mapped. Callers decide how to handle
        unknown dtypes (raise, default, etc.) since behavior differs across
        call sites.
    """
    return TORCH_DTYPE_TO_SCALAR_TYPE.get(dtype)


# The capitalized ScalarType name PyTorch uses in error messages and
# ``Tensor.type()`` (e.g. "Half", not "float16"). These are the ``#name``
# tokens from ``AT_FORALL_SCALAR_TYPES_WITH_COMPLEX_AND_QINTS`` in
# ``c10/core/ScalarType.h``, the same source as the ordinals above.
TORCH_DTYPE_TO_SCALAR_TYPE_NAME: dict[torch.dtype, str] = {
    torch.uint8: "Byte",
    torch.int8: "Char",
    torch.int16: "Short",
    torch.int32: "Int",
    torch.int64: "Long",
    torch.float16: "Half",
    torch.float32: "Float",
    torch.float64: "Double",
    torch.complex64: "ComplexFloat",
    torch.complex128: "ComplexDouble",
    torch.bool: "Bool",
    torch.bfloat16: "BFloat16",
}


def torch_dtype_to_scalar_type_name(dtype: torch.dtype) -> str | None:
    """Return the ``c10::ScalarType`` name for a ``torch.dtype``.

    Matches the spelling PyTorch uses in error messages (e.g. ``torch.float16``
    -> ``"Half"``). Returns ``None`` for unmapped dtypes; callers decide how to
    handle them.
    """
    return TORCH_DTYPE_TO_SCALAR_TYPE_NAME.get(dtype)
