"""Elementwise dynamic NKI adapters (silu / exp / sin / cos / add / mul).

All six share one shape scheme — a [128, H] NEFF per (H, dtype), M dynamic —
differing only in name, operand count, and whether IO needs a contiguous copy.
``make_elementwise_entry`` builds the shared ``compile_fn`` + ``prepare_io``;
each op keeps its OWN ``can_handle`` (add's alpha guard and the binary
shape/dtype checks are per-op and are never generated by the factory).
"""

import torch

from ..adapter_utils import (
    _TILE_M,
    _can_handle_elementwise_2d,
    _compile_or_load_neff,
    _dest_buffer,
    _hidden_compile_key,
    _num_tiles_tensor,
)
from ..registry import DynamicNkiEntry, register_dynamic_nki


# ── per-op can_handle (kept separate; NOT merged into the factory) ──
def _can_handle_unary(x, out=None) -> bool:
    """silu / exp / sin / cos: one 2-D+ neuron tensor, supported dtype, M % 128 == 0."""
    return _can_handle_elementwise_2d(x)


def _can_handle_add(x, y, alpha=1, out=None) -> bool:
    if alpha != 1:  # the a+b kernel can't honor alpha
        return False
    if not isinstance(y, torch.Tensor):
        return False
    return _can_handle_elementwise_2d(x) and x.shape == y.shape and y.dtype == x.dtype


def _can_handle_mul(x, y, out=None) -> bool:
    if not isinstance(y, torch.Tensor):
        return False
    return _can_handle_elementwise_2d(x) and x.shape == y.shape and y.dtype == x.dtype


# ── factory: the shared compile_fn + prepare_io (the mechanical half) ──
def make_elementwise_entry(name, can_handle, *, arity=1, contiguous=False):
    """Build a DynamicNkiEntry for an elementwise op.

    ``name`` derives the wrapper (``dynamic_{name}_nki``) and graph name
    (``dynamic_nki_{name}``); ``arity`` is the operand count (1 unary, 2 binary);
    ``contiguous`` forces a contiguous IO copy. ``can_handle`` is supplied per op
    — the factory never generates it.
    """
    graph_name = f"dynamic_nki_{name}"

    def compile_fn(compile_key):
        """Compile at [128, H] for a (H, dtype) — H + dtype baked, M dynamic."""
        from torch_neuronx.python_ops.torch_mlir.kernel import TorchMlirKernel

        from .. import wrappers

        H, dtype = compile_key  # noqa: N806
        wrapper = getattr(wrappers, f"dynamic_{name}_nki")
        ins = tuple(torch.empty(_TILE_M, H, dtype=dtype, device="neuron") for _ in range(arity))
        nm = torch.tensor([[1]], dtype=torch.int32, device="neuron")
        out = torch.empty(_TILE_M, H, dtype=dtype, device="neuron")

        kernel = TorchMlirKernel(torch_fn=wrapper, op_name=graph_name)
        return _compile_or_load_neff(kernel, graph_name, (*ins, nm), out)

    def prepare_io(*tensors, dest=None, **_):
        """Actual-sized IO (M is a 128-multiple; no padding)."""
        x = tensors[0]
        H = x.shape[-1]  # noqa: N806
        M = x.numel() // H  # noqa: N806
        device = x.device

        def to_2d(t):
            t_2d = t.reshape(-1, H)
            return t_2d.contiguous() if contiguous else t_2d

        ins = tuple(to_2d(tensors[i]) for i in range(arity))
        nm = _num_tiles_tensor(M // _TILE_M, device)
        outputs = (_dest_buffer(dest, M, H, x.dtype, device),)
        return (*ins, nm), outputs, M

    return DynamicNkiEntry(
        compile_fn=compile_fn,
        can_handle=can_handle,
        prepare_io=prepare_io,
        compile_key_fn=_hidden_compile_key,
    )


# ── declarative table: one row per elementwise op ──
# (name, can_handle, arity, contiguous). exp/sin/cos drop the contiguous copy as
# redundant; silu/add/mul keep it.
_ELEMENTWISE_OPS = [
    ("silu", _can_handle_unary, 1, True),
    ("exp", _can_handle_unary, 1, False),
    ("sin", _can_handle_unary, 1, False),
    ("cos", _can_handle_unary, 1, False),
    ("add", _can_handle_add, 2, True),
    ("mul", _can_handle_mul, 2, True),
]


def register():
    for name, can_handle, arity, contiguous in _ELEMENTWISE_OPS:
        register_dynamic_nki(
            name,
            make_elementwise_entry(name, can_handle, arity=arity, contiguous=contiguous),
        )
