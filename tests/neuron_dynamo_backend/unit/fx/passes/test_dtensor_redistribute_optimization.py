class TestPassProperties:
    """Idempotency, false positive safety, and combined patterns."""

    def test_idempotent(self):
        gm = _build_replicate_to_shard_cat(2, 64, 32, 4)
        x = torch.randn(2, 64, 32, dtype=torch.bfloat16)
        gm1 = _run_pass(gm)
        ref = gm1(x)
        gm2 = _run_pass(gm1)
        assert _count(gm2, IDX_SEL) == 0
        torch.testing.assert_close(gm2(x).float(), ref.float(), atol=1e-4, rtol=1e-4)

    def test_unrelated_cat_untouched(self):
        g = Graph()
        a, b = g.placeholder("a"), g.placeholder("b")
        g.output(g.call_function(torch.ops.aten.cat.default, args=([a, b],)))
        gm = GraphModule(torch.nn.Module(), g)
        n_before = len(list(gm.graph.nodes))
        assert len(list(_run_pass(gm).graph.nodes)) == n_before

    def test_unrelated_clone_untouched(self):
        g = Graph()
        a = g.placeholder("a")
        g.output(g.call_function(torch.ops.aten.clone.default, args=(a,)))
        gm = GraphModule(torch.nn.Module(), g)
        n_before = len(list(gm.graph.nodes))
        assert len(list(_run_pass(gm).graph.nodes)) == n_before

    def test_wrong_offsets_untouched(self):
        """Cat with non-arithmetic-progression offsets should be skipped."""
        g = Graph()
        src = g.placeholder("input")
        _set_meta(src, [1, 64, 32])
        flat = g.call_function(torch.ops.aten.view.default, args=(src, [-1]))
        views = []
        for i in range(4):
            idx = _build_indices(g, 1, 16, 32, i * 999, 64 * 32)  # Wrong offsets
            sel = g.call_function(torch.ops.aten.index_select.default, args=(flat, 0, idx))
            views.append(g.call_function(torch.ops.aten.view.default, args=(sel, [1, 16, 32])))
        cat = g.call_function(torch.ops.aten.cat.default, args=(views,))
        _set_meta(cat, [4, 16, 32])
        g.output(cat)
        gm = GraphModule(torch.nn.Module(), g)
        assert _count(_run_pass(gm), IDX_SEL) == 4

    def test_index_select_without_flatten_untouched(self):
        """index_select not preceded by view([-1]) should be skipped."""
        g = Graph()
        src = g.placeholder("input")
        kw = {"dtype": torch.int64, "device": torch.device("cpu"), "pin_memory": False}
        idx = g.call_function(torch.ops.aten.arange.default, args=(10,), kwargs=kw)
        sel = g.call_function(torch.ops.aten.index_select.default, args=(src, 0, idx))
        g.output(g.call_function(torch.ops.aten.clone.default, args=(sel,)))
        gm = GraphModule(torch.nn.Module(), g)
        assert _count(_run_pass(gm), IDX_SEL) == 1

    def test_pass_result_modified_flag(self):
        """PassResult.modified should be True when patterns are found."""
        gm = _build_replicate_to_shard_cat(2, 64, 32, 4)
        result = DTensorRedistributeOptimization().call(gm)
        assert result.modified is True

    def test_pass_result_unmodified_flag(self):
        """PassResult.modified should be False when no patterns match."""
        g = Graph()
        a = g.placeholder("a")
        g.output(g.call_function(torch.ops.aten.clone.default, args=(a,)))
        gm = GraphModule(torch.nn.Module(), g)
        result = DTensorRedistributeOptimization().call(gm)
        assert result.modified is False
