"""Unit tests for DTensorRedistributeOptimization FX pass.

Tests construct FX graphs matching real DTensor redistribution patterns,
run the pass, and verify both numerical correctness and index_select elimination.
"""

import pytest
import torch
from torch.fx import Graph, GraphModule
from torch.fx.passes.shape_prop import TensorMetadata

from torch_neuronx.neuron_dynamo_backend.fx.passes.dtensor_redistribute_optimization import (
    DTensorRedistributeOptimization,
)

IDX_SEL = torch.ops.aten.index_select.default


# ── Helpers ──────────────────────────────────────────────────────────────────


def _set_meta(node, shape, dtype=torch.bfloat16):
    s = 1
    strides = []
    for d in reversed(shape):
        strides.append(s)
        s *= d
    strides.reverse()
    node.meta = {
        "tensor_meta": TensorMetadata(
            dtype=dtype,
            shape=torch.Size(shape),
            stride=tuple(strides),
            requires_grad=False,
            is_quantized=False,
            qparams={},
            memory_format=torch.contiguous_format,
        ),
        "val": torch.empty(shape, dtype=dtype, device="meta"),
    }


def _build_indices(graph, batch, shard_size, hidden, offset, source_dim0_stride):
    """Build DTensor's index computation: multi-dim arange + offset."""
    kw = {"dtype": torch.int64, "device": torch.device("cpu"), "pin_memory": False}
    zeros = graph.call_function(
        torch.ops.aten.zeros.default, args=([batch, shard_size, hidden],), kwargs=kw
    )
    batch_arange = graph.call_function(torch.ops.aten.arange.default, args=(batch,), kwargs=kw)
    batch_indices = graph.call_function(
        torch.ops.aten.view.default, args=(batch_arange, [-1, 1, 1])
    )
    batch_offsets = graph.call_function(
        torch.ops.aten.mul.Tensor, args=(batch_indices, source_dim0_stride)
    )
    accumulated = graph.call_function(torch.ops.aten.add.Tensor, args=(zeros, batch_offsets))
    shard_arange = graph.call_function(torch.ops.aten.arange.default, args=(shard_size,), kwargs=kw)
    shard_indices = graph.call_function(
        torch.ops.aten.view.default, args=(shard_arange, [1, -1, 1])
    )
    shard_offsets = graph.call_function(torch.ops.aten.mul.Tensor, args=(shard_indices, hidden))
    accumulated = graph.call_function(torch.ops.aten.add.Tensor, args=(accumulated, shard_offsets))
    hidden_arange = graph.call_function(torch.ops.aten.arange.default, args=(hidden,), kwargs=kw)
    hidden_indices = graph.call_function(
        torch.ops.aten.view.default, args=(hidden_arange, [1, 1, -1])
    )
    hidden_offsets = graph.call_function(torch.ops.aten.mul.Tensor, args=(hidden_indices, 1))
    accumulated = graph.call_function(torch.ops.aten.add.Tensor, args=(accumulated, hidden_offsets))
    flat_indices = graph.call_function(torch.ops.aten.view.default, args=(accumulated, [-1]))
    return graph.call_function(torch.ops.aten.add.Tensor, args=(flat_indices, offset))


def _count(gm, op):
    return sum(1 for n in gm.graph.nodes if n.target == op)


def _run_pass(gm):
    return DTensorRedistributeOptimization().call(gm).graph_module


# ── Graph Builders ───────────────────────────────────────────────────────────
# These build FX graphs that match the exact patterns generated by DTensor's
# redistribute() when traced through torch.compile. The patterns appear in both
# forward and backward graphs — AOTAutograd traces the backward pass the same way,
# producing identical index_select chains that this pass handles.


def _build_replicate_to_shard_cat(batch, full_dim, hidden, num_chunks):
    """Build Replicate-to-Shard cat pattern as generated by DTensor redistribute (Replicate→Shard).

    Original FX graph (from Qwen3 8B TP4+FSDP16, BS=2):
        source: "bf16[2, 4096, 4096]" = aten.where.self(...)
        view_29: "bf16[33554432]" = aten.view.default(source, [-1])
        # For each chunk i (offset = i * shard * hidden):
        add_19: "i64[8388608]" = aten.add.Tensor(indices, offset)
        index_select_4: "bf16[8388608]" = aten.index_select.default(view_29, 0, add_19)
        view_34: "bf16[2, 1024, 4096]" = aten.view.default(index_select_4, [2, 1024, 4096])
        # ... repeat for all chunks ...
        cat: "bf16[8, 1024, 4096]" = aten.cat.default([view_34, ...])

    Args:
        batch: batch size (B)
        full_dim: full size of the sharded dimension before chunking (N * shard)
        hidden: product of all trailing dimensions after the sharded dim (H)
        num_chunks: number of TP ranks (N)

    After pass (BS=1): source → view([N, shard, H])
    After pass (BS>1): view([B,N,S,H]) → permute([1,0,2,3]) → reshape([N*B,S,H])
    """
    shard = full_dim // num_chunks
    g = Graph()
    src = g.placeholder("input")
    _set_meta(src, [batch, full_dim, hidden])
    flat = g.call_function(torch.ops.aten.view.default, args=(src, [-1]))
    views = []
    for i in range(num_chunks):
        idx = _build_indices(g, batch, shard, hidden, i * shard * hidden, full_dim * hidden)
        sel = g.call_function(torch.ops.aten.index_select.default, args=(flat, 0, idx))
        v = g.call_function(torch.ops.aten.view.default, args=(sel, [batch, shard, hidden]))
        views.append(v)
    cat = g.call_function(torch.ops.aten.cat.default, args=(views,))
    _set_meta(cat, [num_chunks * batch, shard, hidden])
    g.output(cat)
    return GraphModule(torch.nn.Module(), g)


def _build_shard_to_replicate_cat(batch, shard, hidden, num_chunks):
    """Build Shard-to-Replicate cat pattern as generated by DTensor redistribute (Shard→Replicate).

    Original FX graph (from Qwen3 8B TP4+FSDP16, BS=2):
        wait_tensor_3: "bf16[8, 1024, 4096]" = _c10d_functional.wait_tensor.default(all_gather)
        view_131: "bf16[33554432]" = aten.view.default(wait_tensor_3, [-1])
        # For each chunk i (offset = i * batch * shard * hidden):
        add_84: "i64[8388608]" = aten.add.Tensor(indices, offset)
        index_select_20: "bf16[8388608]" = aten.index_select.default(view_131, 0, add_84)
        view_136: "bf16[2, 1024, 4096]" = aten.view.default(index_select_20, [2, 1024, 4096])
        # ... repeat for all chunks ...
        cat_1: "bf16[2, 4096, 4096]" = aten.cat.default([view_136, ...], 1)

    Args:
        batch: batch size (B)
        shard: shard size per rank along the gathered dimension (S)
        hidden: product of all trailing dimensions (H)
        num_chunks: number of TP ranks (N)

    After pass (BS=1): wait_tensor → view([1, N*S, H])
    After pass (BS>1): wait_tensor → view([N, B, S, H]) → permute([1,0,2,3]) → reshape([B, N*S, H])
    """
    g = Graph()
    inp = g.placeholder("input")
    ag = g.call_function(
        torch.ops._c10d_functional.all_gather_into_tensor.default,
        args=(inp, num_chunks, "[[0,1,2,3]]"),
    )
    wait = g.call_function(torch.ops._c10d_functional.wait_tensor.default, args=(ag,))
    _set_meta(wait, [num_chunks * batch, shard, hidden])
    flat = g.call_function(torch.ops.aten.view.default, args=(wait, [-1]))
    chunk_size = batch * shard * hidden
    views = []
    for i in range(num_chunks):
        idx = _build_indices(g, batch, shard, hidden, i * chunk_size, num_chunks * shard * hidden)
        sel = g.call_function(torch.ops.aten.index_select.default, args=(flat, 0, idx))
        v = g.call_function(torch.ops.aten.view.default, args=(sel, [batch, shard, hidden]))
        views.append(v)
    cat = g.call_function(torch.ops.aten.cat.default, args=(views, 1))
    _set_meta(cat, [batch, num_chunks * shard, hidden])
    g.output(cat)
    return GraphModule(torch.nn.Module(), g)


def _build_replicate_to_shard_clone(batch, full_dim, hidden, num_chunks, rank=0):
    """Build Replicate-to-Shard clone pattern as generated by DTensor redistribute
    (Replicate→Shard, single rank).

    Original FX graph (from Qwen3 8B backward, BS=1):
        source: "bf16[16384, 4096]" = aten.view.default(mm_11, [16384, 4096])
        view_flat: "bf16[67108864]" = aten.view.default(source, [-1])
        add_idx: "i64[4194304]" = aten.add.Tensor(indices, rank * shard * hidden)
        index_select: "bf16[4194304]" = aten.index_select.default(view_flat, 0, add_idx)
        view_out: "bf16[1, 4096, 4096]" = aten.view.default(index_select, [1, 4096, 4096])
        clone: "bf16[1, 4096, 4096]" = aten.clone.default(view_out)

    Args:
        batch: batch size (B)
        full_dim: full size of the sharded dimension (N * shard)
        hidden: product of all trailing dimensions (H)
        num_chunks: number of TP ranks (N)
        rank: which rank's shard to select (determines offset)

    After pass: source → slice(shard_dim, rank*S, (rank+1)*S) → clone
    """
    shard = full_dim // num_chunks
    g = Graph()
    src = g.placeholder("input")
    _set_meta(src, [batch, full_dim, hidden])
    flat = g.call_function(torch.ops.aten.view.default, args=(src, [-1]))
    offset = rank * shard * hidden
    idx = _build_indices(g, batch, shard, hidden, offset, full_dim * hidden)
    sel = g.call_function(torch.ops.aten.index_select.default, args=(flat, 0, idx))
    v = g.call_function(torch.ops.aten.view.default, args=(sel, [batch, shard, hidden]))
    clone = g.call_function(torch.ops.aten.clone.default, args=(v,))
    _set_meta(clone, [batch, shard, hidden])
    g.output(clone)
    return GraphModule(torch.nn.Module(), g)


# ── Tests ────────────────────────────────────────────────────────────────────


class TestReplicateToShardCat:
    """Replicate-to-Shard cat: non-wait_tensor source → flatten → index_select x N → cat(dim=0).

    This pattern appears when DTensor prepares input for reduce_scatter by chunking
    a replicated tensor into N pieces (one per TP rank).
    """

    @pytest.mark.parametrize("batch", [1, 2, 4])
    def test_eliminates_index_selects(self, batch):
        gm = _build_replicate_to_shard_cat(batch, 64, 32, 4)
        assert _count(gm, IDX_SEL) == 4
        assert _count(_run_pass(gm), IDX_SEL) == 0

    @pytest.mark.parametrize("batch", [1, 2, 4])
    def test_numerical_accuracy(self, batch):
        gm = _build_replicate_to_shard_cat(batch, 64, 32, 4)
        x = torch.randn(batch, 64, 32, dtype=torch.bfloat16)
        ref = gm(x)
        gm_opt = _run_pass(gm)
        assert _count(gm_opt, IDX_SEL) == 0
        torch.testing.assert_close(gm_opt(x).float(), ref.float(), atol=1e-4, rtol=1e-4)

    def test_real_model_shapes(self):
        """Qwen3 8B dimensions: [2, 4096, 4096] → 4 chunks."""
        gm = _build_replicate_to_shard_cat(2, 4096, 4096, 4)
        x = torch.randn(2, 4096, 4096, dtype=torch.bfloat16)
        ref = gm(x)
        gm_opt = _run_pass(gm)
        assert _count(gm_opt, IDX_SEL) == 0
        torch.testing.assert_close(gm_opt(x).float(), ref.float(), atol=1e-4, rtol=1e-4)


class TestShardToReplicateCat:
    """Shard-to-Replicate cat: wait_tensor source → flatten → index_select x N → cat(dim=1).

    This pattern appears after all_gather when DTensor reassembles shards into
    the full replicated tensor. Only generated for BS>1 (BS=1 uses zero-copy view).
    """

    @pytest.mark.parametrize("batch", [1, 2, 4])
    def test_eliminates_index_selects(self, batch):
        gm = _build_shard_to_replicate_cat(batch, 16, 32, 4)
        assert _count(gm, IDX_SEL) == 4
        assert _count(_run_pass(gm), IDX_SEL) == 0

    @pytest.mark.parametrize("batch", [1, 2, 4])
    def test_numerical_accuracy(self, batch):
        """Verify correctness by comparing against a manually-constructed reference.

        We can't execute wait_tensor on CPU, so we build the expected output
        directly and compare against the pass output (which uses view/permute/reshape
        that ARE executable).
        """
        num_chunks, shard, hidden = 4, 16, 32
        # Simulate all_gather result: [N*B, S, H] in rank-major order
        source = torch.randn(num_chunks * batch, shard, hidden, dtype=torch.bfloat16)

        # Build expected output manually: [B, N*S, H]
        # Shard-to-Replicate reassembles: wait[n*B+b, s, h] → out[b, n*S+s, h]
        expected = torch.zeros(batch, num_chunks * shard, hidden, dtype=torch.bfloat16)
        for n in range(num_chunks):
            for b in range(batch):
                expected[b, n * shard : (n + 1) * shard, :] = source[n * batch + b]

        # Run the pass and extract the replacement subgraph
        gm = _build_shard_to_replicate_cat(batch, shard, hidden, num_chunks)
        gm_opt = _run_pass(gm)
        assert _count(gm_opt, IDX_SEL) == 0

        # Optimized: placeholder → all_gather → wait → view → permute → reshape
        # Replace wait_tensor with identity to make it executable
        for node in gm_opt.graph.nodes:
            if node.target == torch.ops._c10d_functional.wait_tensor.default:
                node.replace_all_uses_with(node.args[0])
                break
        for node in gm_opt.graph.nodes:
            if node.target == torch.ops._c10d_functional.all_gather_into_tensor.default:
                node.replace_all_uses_with(node.args[0])
                break
        gm_opt.graph.eliminate_dead_code()
        gm_opt.recompile()

        out = gm_opt(source)
        torch.testing.assert_close(out.float(), expected.float(), atol=1e-4, rtol=1e-4)


